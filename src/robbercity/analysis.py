"""
Статистичні інструменти, якими атакуючий користується наосліп.

Два різні завдання:

* **Впізнати текст.** Атакуючий, який не знає протоколу, бачить лише три
  шістнадцяткові рядки. Йому потрібен критерій, що автоматично
  відрізняє осмислений англійський текст від випадкових байтів —
  :func:`plausibility`. Саме він дозволяє знайти потрібну комбінацію
  повідомлень перебором, не знаючи заздалегідь, що шукати.

* **Перевірити ключі.** Після зламу корисно переконатися, що відновлені
  ключі справді випадкові: якби вони мали структуру, винним був би
  генератор, а не протокол. Для цього — :func:`byte_entropy`,
  :func:`chi_squared_uniform` і :func:`index_of_coincidence`.

Другий пункт тут принциповий. Висновок роботи полягає саме в тому, що
ключі бездоганні, а зламано протокол; це твердження потрібно підкріпити
вимірюванням, а не заявою.
"""

from __future__ import annotations

import math
from collections import Counter

from .ngrams import default_scorer

__all__ = [
    "printable_ratio",
    "letter_ratio",
    "plausibility",
    "byte_entropy",
    "chi_squared_uniform",
    "index_of_coincidence",
    "looks_like_english",
]

#: Байти, допустимі у звичайному ASCII-тексті: друковані + табуляція,
#: перенесення рядка та повернення каретки.
_PRINTABLE = set(range(0x20, 0x7F)) | {0x09, 0x0A, 0x0D}


# --------------------------------------------------------------------------- #
#  Впізнавання тексту
# --------------------------------------------------------------------------- #

def printable_ratio(data: bytes) -> float:
    """Частка байтів, що є друкованими ASCII-символами (від 0 до 1)."""
    if not data:
        return 0.0
    return sum(1 for b in data if b in _PRINTABLE) / len(data)


def letter_ratio(data: bytes) -> float:
    """Частка латинських літер і пробілів — груба ознака природного тексту."""
    if not data:
        return 0.0
    good = sum(1 for b in data if 65 <= b <= 90 or 97 <= b <= 122 or b == 32)
    return good / len(data)


def plausibility(data: bytes) -> float:
    """
    Наскільки правдоподібно, що ці байти є англійським текстом.

    Повертає логарифмічну правдоподібність за квадриграмами в розрахунку
    на символ. Якщо серед байтів є недруковані, результат одразу
    від'ємно великий: випадкова послідовність майже напевно містить
    байти поза ASCII, тож такий ранній вихід відсікає більшість хибних
    кандидатів без звертання до мовної моделі.

    Нормування на довжину потрібне, щоб можна було порівнювати
    кандидатів різної довжини.
    """
    if not data:
        return -math.inf
    if printable_ratio(data) < 1.0:
        # Штраф пропорційний частці «сміттєвих» байтів: так оцінка
        # лишається монотонною, а не просто нескінченно поганою.
        return -100.0 * (1.0 - printable_ratio(data)) - 10.0
    letters = "".join(chr(b) for b in data if 65 <= b <= 90 or 97 <= b <= 122)
    if len(letters) < 4:
        return -10.0
    return default_scorer().score(letters.upper()) / len(letters)


#: Порогові значення для :func:`looks_like_english`. Обрані за виміряним
#: розділенням на офіційних текстах задачі проти випадкових послідовностей
#: (див. експеримент «Чи можна впізнати текст наосліп»), а не навмання.
MIN_LETTER_RATIO = 0.65
MIN_PLAUSIBILITY = -5.8


def looks_like_english(
    data: bytes,
    min_letters: float = MIN_LETTER_RATIO,
    threshold: float = MIN_PLAUSIBILITY,
) -> bool:
    """
    Бінарна відповідь для автоматичного пошуку: чи це англійський текст?

    Перевіряються три умови одночасно, бо поодинці жодна не є надійною:

    1. усі байти друковані — відсікає випадкові байти (у них друкованих
       близько 37 %, адже діапазон 0x20..0x7E займає 95 значень із 256);
    2. частка літер і пробілів не менша за ``min_letters`` — відсікає
       випадкові *друковані* символи, де ця частка близько 0,55 проти
       0,69..0,96 у справжніх текстах задачі;
    3. логарифмічна правдоподібність за квадриграмами вища за поріг.

    Поодинці межі в пунктах 2 і 3 проходять близько, тому надійність дає
    саме їх кон'юнкція; частоту хибних спрацювань виміряно окремим
    експериментом.
    """
    return (
        printable_ratio(data) == 1.0
        and letter_ratio(data) >= min_letters
        and plausibility(data) > threshold
    )


# --------------------------------------------------------------------------- #
#  Перевірка випадковості
# --------------------------------------------------------------------------- #

def byte_entropy(data: bytes) -> float:
    """
    Емпірична ентропія Шеннона в бітах на байт.

    Для рівномірно випадкових байтів прямує до 8, але на коротких
    послідовностях систематично занижена: при n спостереженнях більшість
    із 256 значень просто не трапляється. Тому абсолютне значення тут
    варто порівнювати не з 8, а з ентропією такої самої кількості
    справді випадкових байтів.
    """
    if not data:
        return 0.0
    counts = Counter(data)
    n = len(data)
    return -sum((c / n) * math.log2(c / n) for c in counts.values())


def chi_squared_uniform(data: bytes) -> float:
    """
    Статистика хі-квадрат байтів відносно рівномірного розподілу.

    Очікуване значення для справді рівномірних даних дорівнює числу
    степенів вільності, тобто 255.
    """
    if not data:
        return math.inf
    counts = Counter(data)
    expected = len(data) / 256.0
    return sum((counts.get(b, 0) - expected) ** 2 / expected for b in range(256))


def index_of_coincidence(data: bytes) -> float:
    """
    Ймовірність збігу двох навмання взятих байтів.

    Для рівномірних байтів прямує до 1/256 ≈ 0.0039, для англійського
    тексту — приблизно на порядок більша. Метрика зручна тим, що не
    залежить від перестановки значень: шифр простою заміною її не
    змінює, а XOR з випадковим ключем — руйнує.
    """
    n = len(data)
    if n < 2:
        return 0.0
    counts = Counter(data)
    return sum(c * (c - 1) for c in counts.values()) / (n * (n - 1))
