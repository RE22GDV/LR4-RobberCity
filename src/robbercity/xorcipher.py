"""
Потоковий шифр XOR і одноразовий блокнот (one-time pad).

Операція тут одна, і вона ж є і шифруванням, і розшифруванням:

    c[i] = m[i] XOR k[i]
    m[i] = c[i] XOR k[i]

Саме ця симетрія згодом і зруйнує протокол: шифрування та зняття
шифру — та сама дія, тому порядок операцій не має жодного значення.

Усі функції працюють із ``bytes``. Перетворення в шістнадцятковий рядок
і назад винесено окремо, бо саме в такому вигляді повідомлення
передаються в умові задачі.
"""

from __future__ import annotations

import secrets

__all__ = [
    "xor_bytes",
    "xor_all",
    "random_key",
    "encrypt",
    "decrypt",
    "from_hex",
    "to_hex",
    "to_text",
    "from_text",
]


# --------------------------------------------------------------------------- #
#  Базова операція
# --------------------------------------------------------------------------- #

def xor_bytes(left: bytes, right: bytes) -> bytes:
    """
    Побайтове XOR двох послідовностей однакової довжини.

    Довжини зобов'язані збігатися: мовчазне обрізання до коротшої
    послідовності — класичне джерело помилок у подібних задачах, тому
    тут це помилка, а не «особливість».
    """
    if len(left) != len(right):
        raise ValueError(
            "довжини не збігаються: %d і %d байтів" % (len(left), len(right))
        )
    return bytes(a ^ b for a, b in zip(left, right))


def xor_all(*chunks: bytes) -> bytes:
    """
    XOR довільної кількості послідовностей однакової довжини.

    Операція асоціативна та комутативна, тому порядок аргументів не
    впливає на результат — це перевіряється окремим тестом.
    """
    if not chunks:
        raise ValueError("потрібна хоча б одна послідовність")
    result = chunks[0]
    for chunk in chunks[1:]:
        result = xor_bytes(result, chunk)
    return result


# --------------------------------------------------------------------------- #
#  Ключі
# --------------------------------------------------------------------------- #

def random_key(length: int) -> bytes:
    """
    Криптографічно стійкий ключ довжиною рівно ``length`` байтів.

    Саме такий ключ вимагає одноразовий блокнот: випадковий, довжиною з
    повідомлення, використаний один раз. Усі ключі в цій роботі — саме
    такі; зламано буде не їх, а протокол, у якому вони застосовані.
    """
    if length < 0:
        raise ValueError("довжина ключа не може бути від'ємною")
    return secrets.token_bytes(length)


# --------------------------------------------------------------------------- #
#  Шифрування = розшифрування
# --------------------------------------------------------------------------- #

def encrypt(message: bytes, key: bytes) -> bytes:
    """Накласти ключ. Те саме, що :func:`decrypt` — операція самообернена."""
    return xor_bytes(message, key)


def decrypt(ciphertext: bytes, key: bytes) -> bytes:
    """Зняти ключ. Те саме, що :func:`encrypt`."""
    return xor_bytes(ciphertext, key)


# --------------------------------------------------------------------------- #
#  Перетворення представлень
# --------------------------------------------------------------------------- #

def from_hex(digits: str) -> bytes:
    """
    Шістнадцятковий рядок -> байти.

    Приймає рядок із пробілами та переносами, але довжина має бути
    парною: кожні дві цифри — один байт (00..FF).
    """
    cleaned = "".join(digits.split())
    if len(cleaned) % 2:
        raise ValueError("непарна кількість шістнадцяткових цифр: %d" % len(cleaned))
    return bytes.fromhex(cleaned)


def to_hex(data: bytes) -> str:
    """Байти -> шістнадцятковий рядок малими літерами."""
    return data.hex()


def to_text(data: bytes, encoding: str = "ascii") -> str:
    """Байти -> текст. За умовою задачі відкритий текст є ASCII."""
    return data.decode(encoding)


def from_text(text: str, encoding: str = "ascii") -> bytes:
    """Текст -> байти."""
    return text.encode(encoding)
